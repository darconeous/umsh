import Foundation
import SQLite3

/// Migrates a fresh database through every Swift migration and prints the
/// schema it ends at, in the form the Rust store's baseline is built from.
///
/// Objects are ordered tables first, then indexes, triggers, and views, each
/// by name, so the output only changes when the schema does. SQLite's own
/// objects (`sqlite_sequence`, automatic indexes) are left out; SQLite makes
/// those itself.
@main
struct StoreSchemaDump {
    static func main() throws {
        let root = FileManager.default.temporaryDirectory
            .appendingPathComponent("umsh-schema-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }
        let path = root.appendingPathComponent("application.sqlite").path

        // Opening runs the migrations; the store closes on release.
        do {
            _ = try SQLiteApplicationStore(path: path)
        }

        var database: OpaquePointer?
        guard sqlite3_open_v2(path, &database, SQLITE_OPEN_READONLY, nil) == SQLITE_OK,
              let database
        else {
            fatalError("cannot reopen \(path)")
        }
        defer { sqlite3_close(database) }

        var versionStatement: OpaquePointer?
        guard sqlite3_prepare_v2(database, "PRAGMA user_version", -1, &versionStatement, nil)
            == SQLITE_OK, sqlite3_step(versionStatement) == SQLITE_ROW
        else {
            fatalError(String(cString: sqlite3_errmsg(database)))
        }
        let version = sqlite3_column_int(versionStatement, 0)
        sqlite3_finalize(versionStatement)

        var statement: OpaquePointer?
        let query = """
            SELECT sql FROM sqlite_master
            WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
            ORDER BY CASE type
                WHEN 'table' THEN 0 WHEN 'index' THEN 1
                WHEN 'trigger' THEN 2 ELSE 3 END,
                name
            """
        guard sqlite3_prepare_v2(database, query, -1, &statement, nil) == SQLITE_OK else {
            fatalError(String(cString: sqlite3_errmsg(database)))
        }
        defer { sqlite3_finalize(statement) }

        var output = """
            -- The application store's schema at version \(version), exactly as the
            -- Swift store's migrations leave it. Generated by
            -- scripts/ios/dump-store-schema.sh; do not edit.

            """
        while sqlite3_step(statement) == SQLITE_ROW {
            output += "\n" + String(cString: sqlite3_column_text(statement, 0)) + ";\n"
        }
        FileHandle.standardOutput.write(Data(output.utf8))
    }
}
